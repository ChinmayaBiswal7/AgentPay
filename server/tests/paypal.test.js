import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import dotenv from 'dotenv';
import { getAccessToken, createOrder, getOrder } from '../services/paypalService.js';
import { calculateOrderSummary } from '../services/catalogService.js';

dotenv.config();

describe('PayPal Sandbox Integration', () => {
  it('should authenticate with PayPal Sandbox and acquire OAuth Bearer token', async () => {
    const token = await getAccessToken();
    assert.ok(token, 'Access token should not be null');
    assert.ok(typeof token === 'string' && token.length > 20, 'Access token should be a valid string');
  });

  it('should create an authentic order on PayPal Sandbox with server-calculated price', async () => {
    // Generate verified order summary for ThinkBook ($649.99)
    const summary = calculateOrderSummary([{ productId: 'lap-01', quantity: 1 }]);

    const paypalOrder = await createOrder(summary, { source: 'unit_test' });

    assert.ok(paypalOrder.orderId, 'Order ID must be generated by PayPal');
    assert.equal(paypalOrder.status, 'CREATED', 'Initial PayPal order status should be CREATED');
    assert.ok(Array.isArray(paypalOrder.links), 'PayPal should return action links (approval_url, etc)');

    // Verify order can be queried back
    const retrieved = await getOrder(paypalOrder.orderId);
    assert.ok(retrieved);
  });

  it('should fail cleanly when invalid product is ordered', () => {
    assert.throws(() => {
      calculateOrderSummary([{ productId: 'non-existent-id', quantity: 1 }]);
    });
  });
});
